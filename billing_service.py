    @staticmethod
    def _billing_datetime(
        value: Any,
    ) -> Any:
        from datetime import datetime

        raw = str(
            value
            or ""
        ).strip()

        if not raw:
            return None

        if raw.endswith("Z"):
            raw = (
                raw[:-1]
                + "+00:00"
            )

        try:
            result = (
                datetime.fromisoformat(
                    raw
                )
            )
        except ValueError:
            return None

        if result.tzinfo is None:
            result = result.replace(
                tzinfo=(
                    datetime.now()
                    .astimezone()
                    .tzinfo
                )
            )

        return result

    @staticmethod
    def _add_calendar_months(
        value: Any,
        months_count: int,
        *,
        anchor_day: int | None = None,
    ) -> Any:
        from calendar import monthrange

        months = int(
            months_count
        )

        month_index = (
            value.month
            - 1
            + months
        )

        year = (
            value.year
            + month_index // 12
        )

        month = (
            month_index % 12
            + 1
        )

        target_day = (
            int(anchor_day)
            if anchor_day is not None
            else int(value.day)
        )

        if not 1 <= target_day <= 31:
            raise SubscriptionError(
                "Billing anchor day must be between 1 and 31."
            )

        day = min(
            target_day,
            monthrange(
                year,
                month,
            )[1],
        )

        return value.replace(
            year=year,
            month=month,
            day=day,
        )

