    @staticmethod
    def _file_sha256(
        file_path: Path,
    ) -> str:
        digest = hashlib.sha256()

        with file_path.open(
            "rb"
        ) as stream:
            for chunk in iter(
                lambda: stream.read(
                    1024 * 1024
                ),
                b"",
            ):
                digest.update(
                    chunk
                )

        return digest.hexdigest()

