def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value

    if value is None:
        return False

    if isinstance(value, (int, float)):
        return value != 0

    text = str(value).strip().casefold()

    if text in {
        "1",
        "true",
        "yes",
        "on",
    }:
        return True

    if text in {
        "",
        "0",
        "false",
        "no",
        "off",
    }:
        return False

    raise SubscriptionError(
        "???????????? ?????????? ????????."
    )


