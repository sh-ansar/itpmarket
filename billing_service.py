    def payment_proof_file(
        self,
        proof_id: int,
        tenant_id: int,
    ) -> dict[str, Any]:
        conn = self._connect()

        try:
            row = conn.execute(
                """SELECT *
                   FROM subscription_payment_proofs
                   WHERE id=?
                     AND tenant_id=?""",
                (
                    int(proof_id),
                    int(tenant_id),
                ),
            ).fetchone()

        finally:
            conn.close()

        if not row:
            raise SubscriptionError(
                "\u041f\u043b\u0430\u0442\u0451\u0436\u043d\u044b\u0439 "
                "\u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442 "
                "\u043d\u0435 "
                "\u043d\u0430\u0439\u0434\u0435\u043d."
            )

        proof = (
            self
            ._payment_proof_dict(
                row
            )
        )

        path = (
            self
            ._normalize_payment_proof_file(
                Path(
                    str(
                        proof.get(
                            "stored_path"
                        )
                        or ""
                    )
                )
            )
        )

        if not path.is_file():
            raise SubscriptionError(
                "\u0424\u0430\u0439\u043b "
                "\u043f\u043b\u0430\u0442\u0451\u0436\u043d\u043e\u0433\u043e "
                "\u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442\u0430 "
                "\u043d\u0435 "
                "\u043d\u0430\u0439\u0434\u0435\u043d."
            )

        actual_sha256 = (
            hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
        )

        stored_sha256 = str(
            proof.get(
                "sha256"
            )
            or ""
        )

        if (
            not stored_sha256
            or actual_sha256
            != stored_sha256
        ):
            raise SubscriptionError(
                "\u041a\u043e\u043d\u0442\u0440\u043e\u043b\u044c\u043d\u0430\u044f "
                "\u0441\u0443\u043c\u043c\u0430 "
                "\u043f\u043b\u0430\u0442\u0451\u0436\u043d\u043e\u0433\u043e "
                "\u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442\u0430 "
                "\u043d\u0435 "
                "\u0441\u043e\u0432\u043f\u0430\u0434\u0430\u0435\u0442."
            )

        return {
            "proof": proof,
            "path": path,
            "sha256": actual_sha256,
            "size": path.stat().st_size,
        }

