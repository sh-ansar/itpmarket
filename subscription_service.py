class SubscriptionError(ValueError):
    pass


class SubscriptionLimitError(SubscriptionError):
    pass


def now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def _parse_time(value: Any) -> datetime | None:
    raw = str(value or "").strip()
    if not raw:
        return None
    try:
        parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.astimezone()
    return parsed


def _optional_limit(value: Any, *, maximum: int = 10_000_000) -> int | None:
    if value in (None, "", "unlimited"):
        return None
    number = int(value)
    if number < 0 or number > maximum:
        raise SubscriptionError(f"Лимит должен быть от 0 до {maximum} или пустым для безлимита.")
    return number


class SubscriptionService:
    def __init__(self, db_path: Path):
        self.db_path = Path(db_path)
        self.ensure_payment_schema()
        self.ensure_seed_data()

    def _connect(self) -> sqlite3.Connection:
        conn = connect_database(self.db_path, timeout=30)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys=ON")
        conn.execute("PRAGMA busy_timeout=30000")
        return conn

    def ensure_payment_schema(self) -> None:
        conn = self._connect()
        try:
            if isinstance(conn, PostgresConnection):
                conn.execute(
                    """CREATE TABLE IF NOT EXISTS subscription_payments(
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
                           subscription_id BIGINT NOT NULL UNIQUE REFERENCES tenant_subscriptions(id) ON DELETE CASCADE,
                           amount DOUBLE PRECISION NOT NULL DEFAULT 0,
                           currency TEXT NOT NULL DEFAULT 'KZT',status TEXT NOT NULL DEFAULT 'confirmed',
                           paid_at TEXT NOT NULL,period_start TEXT NOT NULL,period_end TEXT NOT NULL,
                           term_days INTEGER NOT NULL,months_count DOUBLE PRECISION NOT NULL DEFAULT 1,
                           confirmed_by BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
                           note TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL
                       )"""
                )
            else:
                conn.execute(
                    """CREATE TABLE IF NOT EXISTS subscription_payments(
                           id INTEGER PRIMARY KEY AUTOINCREMENT,tenant_id INTEGER NOT NULL,
                           subscription_id INTEGER NOT NULL UNIQUE,amount REAL NOT NULL DEFAULT 0,
                           currency TEXT NOT NULL DEFAULT 'KZT',status TEXT NOT NULL DEFAULT 'confirmed',
                           paid_at TEXT NOT NULL,period_start TEXT NOT NULL,period_end TEXT NOT NULL,
                           term_days INTEGER NOT NULL,months_count REAL NOT NULL DEFAULT 1,
                           confirmed_by INTEGER,note TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL,
                           FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
                           FOREIGN KEY(subscription_id) REFERENCES tenant_subscriptions(id) ON DELETE CASCADE,
                           FOREIGN KEY(confirmed_by) REFERENCES app_users(id) ON DELETE SET NULL
                       )"""
                )
            conn.execute(
                """CREATE INDEX IF NOT EXISTS idx_subscription_payments_time
                   ON subscription_payments(paid_at DESC,tenant_id)"""
            )
            conn.commit()
        finally:
            conn.close()

    @staticmethod
    def _plan_row(conn: sqlite3.Connection, plan_id: int) -> dict[str, Any]:
        row = conn.execute("SELECT * FROM subscription_plans WHERE id=?", (int(plan_id),)).fetchone()
        if not row:
            raise SubscriptionError("Пакет не найден.")
        value = dict(row)
        features = [dict(item) for item in conn.execute(
            """SELECT pf.feature_code,pf.is_enabled,pf.limit_value,pf.config_json,
                      f.name,f.description,f.category
               FROM subscription_plan_features pf
               JOIN subscription_features f ON f.code=pf.feature_code
               WHERE pf.plan_id=? ORDER BY f.category,f.name""",
            (int(plan_id),),
        ).fetchall()]
        for item in features:
            try:
                item["config"] = json.loads(str(item.pop("config_json") or "{}"))
            except json.JSONDecodeError:
                item["config"] = {}
            item["is_enabled"] = bool(item["is_enabled"])
        limits = [dict(item) for item in conn.execute(
            """SELECT marketplace_code,is_enabled,position_limit,daily_operation_limit
               FROM subscription_plan_marketplace_limits
               WHERE plan_id=? ORDER BY marketplace_code""",
            (int(plan_id),),
        ).fetchall()]
        for item in limits:
            item["is_enabled"] = bool(item["is_enabled"])
        value.update({
            "is_public": bool(value["is_public"]),
            "is_active": bool(value["is_active"]),
            "features": features,
            "marketplaces": limits,
        })
        return value

